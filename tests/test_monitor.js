'use strict';
const assert = require('node:assert/strict');
const core = require('../web/monitor-core.js');
assert.equal(core.integrate(0,1000,3600),1,'1 kW for an hour is 1 kWh');
assert.equal(core.integrate(2,null,3600),2,'Missing readings do not become fabricated zero-consumption samples');
assert.throws(()=>core.integrate(0,-1,10));
const empty=core.snapshot(new Set(),'day',0);
assert.equal(empty.watts,null);
assert.equal(empty.online,0);
assert.equal(empty.evidence,'simulated');
const connected=new Set(['shower','fridge','ac']);
const bath=core.snapshot(connected,'bath',0);
assert.equal(bath.readings.find(d=>d.id==='shower').watts,5500);
assert.equal(core.snapshot(connected,'day',0).readings.find(d=>d.id==='shower').watts,0);
assert.equal(core.snapshot(connected,'night',0).rooms.bedroom.connected,1);
assert.equal(bath.rooms.bathroom.watts,5500);
assert.equal(bath.readings.find(d=>d.id==='tv').watts,null,'Disconnected device is unknown, not off');
assert.equal(bath.watts,bath.readings.reduce((total,d)=>total+(d.watts??0),0));
console.log('Monitor checks passed: energy units, missing data, simulated provenance, scenarios, room totals, disconnected sensors.');
